package com.pfe.Entity;

public class CrmBoutiqueProfile {
    private String boutiqueName;
    private String boutiqueCode;
    private String address;

    public String getBoutiqueName() { return boutiqueName; }
    public void setBoutiqueName(String boutiqueName) { this.boutiqueName = boutiqueName; }

    public String getBoutiqueCode() { return boutiqueCode; }
    public void setBoutiqueCode(String boutiqueCode) { this.boutiqueCode = boutiqueCode; }

    public String getAddress() { return address; }
    public void setAddress(String address) { this.address = address; }
}
